// Writes src/data/communityIconGlyphs.ts from Lucide's icons (ISC licence). Run after changing the list.
// Only the server route reads the result, so none of these drawings reach the browser's JavaScript.
import { writeFileSync } from 'node:fs';

const GLYPHS = {
    football: 'volleyball', trophy: 'trophy', music: 'music', mic: 'mic', plane: 'plane', house: 'house', briefcase: 'briefcase', code: 'code',
    chip: 'cpu', chart: 'trending-up', wallet: 'wallet', bank: 'landmark', shop: 'store', food: 'soup', graduation: 'graduation-cap', book: 'book-open',
    heart: 'heart', vote: 'vote', news: 'newspaper', tv: 'tv', film: 'film', gamepad: 'gamepad-2', camera: 'camera', health: 'stethoscope',
    fitness: 'dumbbell', church: 'church', mosque: 'moon-star', car: 'car', bike: 'bike', baby: 'baby', fashion: 'shirt', art: 'palette',
    chat: 'message-circle', people: 'users', globe: 'globe', language: 'languages', law: 'scale', farm: 'sprout', pets: 'dog', idea: 'lightbulb', rocket: 'rocket', shield: 'shield',
};

const out = {};
for (const [name, file] of Object.entries(GLYPHS)) {
    const { __iconNode } = await import(`lucide-react/dist/esm/icons/${file}.js`);
    out[name] = __iconNode
        .map(([tag, { key, ...attrs }]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${v}"`).join(' ')}/>`)
        .join('');
}
writeFileSync(
    new URL('../src/data/communityIconGlyphs.ts', import.meta.url),
    `// Generated by scripts/build-community-icons.mjs from Lucide (ISC licence)\nexport const GLYPHS: Record<string, string> = ${JSON.stringify(out, null, 4)};\n`
);
